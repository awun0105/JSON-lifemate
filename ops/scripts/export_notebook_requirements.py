"""Sinh `ops/requirements/notebook.txt` từ `uv.lock`: các thư viện chính và extra `tokenizer`, có ghim phiên bản.

Cách dùng:
    uv run python ops/scripts/export_notebook_requirements.py

Nội dung chính:
- `resolve`: duyệt phụ thuộc bắc cầu và ghim phiên bản.
- `render`: tạo nội dung file đầu ra.
- `main`: đọc `uv.lock`, ghi file và in đường dẫn.

Cách hoạt động:
1. Đọc `uv.lock` (TOML) thành dict các gói.
2. Bắt đầu từ các phụ thuộc của gói lifemate và extra `tokenizer`, duyệt dần toàn bộ phụ thuộc bắc cầu (kể cả
   extra của từng gói), bỏ các gói khớp `EXCLUDE_PATTERNS`.
3. Ghi phần đầu cố định cùng các dòng `ten==phien_ban` đã sắp xếp vào `notebook.txt`.

Lưu ý:
- Các gói GPU (torch, CUDA, vllm) bị loại: image Kaggle/Colab có sẵn torch riêng, còn vllm chỉ được cài riêng
  trong notebook khi có GPU.
- Environment marker trong `uv.lock` bị bỏ qua, nên danh sách là hợp của mọi nền tảng.
"""

from __future__ import annotations

import fnmatch
import tomllib
from pathlib import Path

# Thư mục gốc repo, file lock nguồn và file đích.
REPO_ROOT = Path(__file__).resolve().parent.parent.parent
LOCK = REPO_ROOT / "uv.lock"
OUT = REPO_ROOT / "ops" / "requirements" / "notebook.txt"
PROJECT = "lifemate"
EXTRAS = ("tokenizer",)
# Mẫu tên gói GPU bị loại (notebook dùng torch có sẵn, vllm cài riêng).
EXCLUDE_PATTERNS = ("torch", "torch*", "nvidia-*", "triton", "cuda-*", "cupy*", "vllm", "xformers", "flashinfer*")

# Phần đầu ghi vào file sinh ra; giữ tiếng Anh vì đây là nội dung đầu ra.
HEADER = """\
# GENERATED by ops/scripts/export_notebook_requirements.py from uv.lock. Do not edit.
# Regenerate: uv run python ops/scripts/export_notebook_requirements.py
# Main deps + extra 'tokenizer'; torch/nvidia/triton/cuda/vllm are excluded on purpose.
"""


def excluded(name: str) -> bool:
    """Trả về `True` nếu tên gói khớp một trong các mẫu bị loại."""
    return any(fnmatch.fnmatch(name, pat) for pat in EXCLUDE_PATTERNS)


def resolve(lock: dict) -> dict[str, str]:
    """Duyệt phụ thuộc bắc cầu từ gói lifemate và trả về dict {tên gói: phiên bản}."""
    packages = {p["name"]: p for p in lock["package"]}
    root = packages[PROJECT]
    queue: list[dict] = list(root.get("dependencies", []))
    for extra in EXTRAS:
        queue += root.get("optional-dependencies", {}).get(extra, [])
    pinned: dict[str, str] = {}
    # Ghi nhớ cặp (tên, extra) đã xử lý để không duyệt lặp.
    seen: set[tuple[str, tuple[str, ...]]] = set()
    while queue:
        dep = queue.pop()
        name, extras = dep["name"], tuple(dep.get("extra", []))
        if (name, extras) in seen or excluded(name):
            continue
        seen.add((name, extras))
        pkg = packages[name]
        pinned[name] = pkg["version"]
        # Thêm phụ thuộc của gói này và của các extra được yêu cầu vào hàng đợi.
        queue += pkg.get("dependencies", [])
        for extra in extras:
            queue += pkg.get("optional-dependencies", {}).get(extra, [])
    return pinned


def render(pinned: dict[str, str]) -> str:
    """Tạo nội dung file: phần đầu cố định và một dòng `ten==phien_ban` cho mỗi gói, theo thứ tự tên."""
    return HEADER + "".join(f"{n}=={v}\n" for n, v in sorted(pinned.items()))


def main() -> None:
    """Đọc `uv.lock`, sinh `notebook.txt` và in đường dẫn file đã ghi."""
    lock = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(resolve(lock)), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
